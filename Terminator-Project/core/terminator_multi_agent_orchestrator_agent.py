class ReportManager:
    """
    Manages reports with version control and reuse enforcement.
    Limits the number of copies and encourages report reuse.
    """

    def __init__(self, max_copies_per_report: int = 3):
        self.reports: Dict[str, Report] = {}
        self.report_versions: Dict[str, List[Report]] = defaultdict(list)
        self.max_copies = max_copies_per_report
        self.default_save_path = "/Users/reeazmahmud/Desktop/Terminator-Project/reports"
        os.makedirs(self.default_save_path, exist_ok=True)

    def create_report(
        self,
        task_id: str,
        title: str,
        content: str,
        generated_by: List[str],
        metadata: Optional[Dict[str, Any]] = None
    ) -> Report:
        """Create a new report or update existing one"""
        # Check if report for this task already exists
        existing_report = self._find_report_by_task(task_id)

        if existing_report:
            # Update existing report (reuse pattern)
            return self.update_report(existing_report.report_id, content, generated_by)

        # Create new report
        report_id = f"report_{task_id}_{int(time.time()*1000)}"
        report = Report(
            report_id=report_id,
            title=title,
            task_id=task_id,
            generated_by=generated_by,
            content=content,
            metadata=metadata or {}
        )

        self.reports[report_id] = report
        self.report_versions[task_id].append(report)

        print(f"📄 Created report: {report_id} for task {task_id}")
        return report

    def update_report(
        self,
        report_id: str,
        content: str,
        updated_by: List[str]
    ) -> Report:
        """Update an existing report (encourages reuse)"""
        if report_id not in self.reports:
            raise ValueError(f"Report {report_id} not found")

        report = self.reports[report_id]
        report.content = content
        report.version += 1
        report.updated_at = datetime.now().isoformat()

        # Add updaters to generated_by list
        for agent in updated_by:
            if agent not in report.generated_by:
                report.generated_by.append(agent)

        # Store as new version
        self.report_versions[report.task_id].append(report)

        print(f"📝 Updated report: {report_id} (version {report.version})")
        return report

    def save_report(
        self,
        report_id: str,
        save_path: Optional[str] = None,
        force_copy: bool = False
    ) -> str:
        """
        Save report to file. Enforces copy limits unless force_copy=True.
        Returns the file path where report was saved.
        """
        if report_id not in self.reports:
            raise ValueError(f"Report {report_id} not found")

        report = self.reports[report_id]

        # Check copy limit
        existing_copies = self._count_report_copies(report.task_id)
        if existing_copies >= self.max_copies and not force_copy:
            raise ValueError(
                f"Copy limit reached ({self.max_copies} copies). "
                f"Use update_report() instead or set force_copy=True."
            )

        # Determine save path
        if save_path:
            os.makedirs(os.path.dirname(save_path), exist_ok=True)
            file_path = save_path
        elif report.file_path:
            # Overwrite existing file (reuse pattern)
            file_path = report.file_path
        else:
            # Create new file
            filename = f"{report.task_id}_v{report.version}_{int(time.time())}.json"
            file_path = os.path.join(self.default_save_path, filename)

        # Save report
        report_data = asdict(report)
        with open(file_path, 'w') as f:
            json.dump(report_data, f, indent=2)

        report.file_path = file_path
        print(f"💾 Saved report to: {file_path}")
        return file_path

    def get_report(self, report_id: str) -> Optional[Report]:
        """Get a report by ID"""
        return self.reports.get(report_id)

    def get_reports_for_task(self, task_id: str) -> List[Report]:
        """Get all report versions for a task"""
        return self.report_versions.get(task_id, [])

    def _find_report_by_task(self, task_id: str) -> Optional[Report]:
        """Find the latest report for a task"""
        versions = self.report_versions.get(task_id, [])
        return versions[-1] if versions else None

    def _count_report_copies(self, task_id: str) -> int:
        """Count how many file copies exist for a task's reports"""
        count = 0
        for report in self.report_versions.get(task_id, []):
            if report.file_path and os.path.exists(report.file_path):
                count += 1
        return count

    def get_summary(self) -> Dict[str, Any]:
        """Get summary of all reports"""
        return {
            "total_reports": len(self.reports),
            "total_tasks_with_reports": len(self.report_versions),
            "max_copies_allowed": self.max_copies,
            "reports_by_task": {
                task_id: len(versions)
                for task_id, versions in self.report_versions.items()
            }
        }


