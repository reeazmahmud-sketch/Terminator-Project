class TaskStatus(str, Enum):
    """Status of a task"""
    PENDING = "pending"
    ASSIGNED = "assigned"
    IN_PROGRESS = "in_progress"
    COMPLETED = "completed"
    BLOCKED = "blocked"
    FAILED = "failed"
    CANCELLED = "cancelled"


class TaskPriority(str, Enum):
    """Priority levels for tasks"""
    CRITICAL = "critical"
    HIGH = "high"
    NORMAL = "normal"
    LOW = "low"


@dataclass
class TaskMetrics:
    """Time and performance metrics for a task"""
    created_at: str
    started_at: Optional[str] = None
    completed_at: Optional[str] = None
    estimated_duration_seconds: float = 0.0
    actual_duration_seconds: float = 0.0
    progress_percent: float = 0.0

    def get_elapsed_time(self) -> float:
        """Get elapsed time in seconds"""
        if not self.started_at:
            return 0.0

        start = datetime.fromisoformat(self.started_at)
        end = datetime.fromisoformat(self.completed_at) if self.completed_at else datetime.now()
        return (end - start).total_seconds()

    def get_time_remaining(self) -> float:
        """Get estimated time remaining in seconds"""
        if self.estimated_duration_seconds == 0:
            return 0.0

        elapsed = self.get_elapsed_time()
        return max(0.0, self.estimated_duration_seconds - elapsed)


@dataclass
class Task:
    """Represents a task that can be assigned to agents"""
    task_id: str
    title: str
    description: str
    assigned_agents: List[str] = field(default_factory=list)
    status: TaskStatus = TaskStatus.PENDING
    priority: TaskPriority = TaskPriority.NORMAL
    parent_task_id: Optional[str] = None  # For sub-tasks
    sub_task_ids: List[str] = field(default_factory=list)
    metrics: TaskMetrics = field(default_factory=lambda: TaskMetrics(created_at=datetime.now().isoformat()))
    requirements: List[str] = field(default_factory=list)
    deliverables: List[str] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def add_note(self, note: str, author: str = "system") -> None:
        """Add a note to the task"""
        timestamp = datetime.now().isoformat()
        self.notes.append(f"[{timestamp}] [{author}] {note}")

    def is_sub_task(self) -> bool:
        """Check if this is a sub-task"""
        return self.parent_task_id is not None

    def has_sub_tasks(self) -> bool:
        """Check if this task has sub-tasks"""
        return len(self.sub_task_ids) > 0


@dataclass
class AgentWorkload:
    """Track an agent's current workload"""
    agent_name: str
    assigned_tasks: List[str] = field(default_factory=list)
    active_task_id: Optional[str] = None
    total_tasks_completed: int = 0
    total_time_worked_seconds: float = 0.0
    current_utilization: float = 0.0  # 0.0 to 1.0
    last_heartbeat: str = field(default_factory=lambda: datetime.now().isoformat())


@dataclass
class Report:
    """Represents a report generated by agents"""
    report_id: str
    title: str
    task_id: str
    generated_by: List[str]  # List of agent names
    content: str
    version: int = 1
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())
    updated_at: str = field(default_factory=lambda: datetime.now().isoformat())
    file_path: Optional[str] = None
    metadata: Dict[str, Any] = field(default_factory=dict)


